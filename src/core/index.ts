import type { Frontmatter, MemoryType } from "./memory.ts";
import { MEMORY_TYPES, parseMemoryFile } from "./memory.ts";
import { INDEX_FILE } from "./store.ts";
import type { MemoryStore } from "./store.ts";

/**
 * The index (`MEMORY.md`) is *derived*, never hand-edited. Agents write memory
 * files; reindex regenerates the index from their frontmatter. This keeps the
 * one shared, mutable file off the concurrent-write path.
 */

interface Pointer {
  file: string;
  frontmatter: Frontmatter;
}

const TYPE_HEADINGS: Record<MemoryType, string> = {
  user: "User",
  feedback: "Feedback",
  project: "Project",
  reference: "Reference",
};

export function renderIndex(pointers: Pointer[]): string {
  const lines: string[] = [
    "# Memory index",
    "",
    "<!-- Generated by mdmem from memory frontmatter. Do not edit by hand. -->",
    "",
  ];

  if (pointers.length === 0) {
    lines.push("_No memories yet._", "");
    return lines.join("\n");
  }

  for (const type of MEMORY_TYPES) {
    const group = pointers
      .filter((p) => p.frontmatter.metadata.type === type)
      .toSorted((a, b) => a.frontmatter.name.localeCompare(b.frontmatter.name));
    if (group.length === 0) {
      continue;
    }
    lines.push(`## ${TYPE_HEADINGS[type]}`, "");
    for (const p of group) {
      lines.push(
        `- [${p.frontmatter.name}](${p.file}) — ${p.frontmatter.description}`
      );
    }
    lines.push("");
  }

  return lines.join("\n");
}

export async function reindex(store: MemoryStore): Promise<string> {
  const files = await store.listMemoryFiles();
  // Read the memories concurrently, then parse them in file order.
  const raws = await Promise.all(
    files.map(async (file) => ({ file, raw: await store.view(file) }))
  );
  const pointers: Pointer[] = raws.map(({ file, raw }) => ({
    file,
    frontmatter: parseMemoryFile(file, raw).frontmatter,
  }));
  const content = renderIndex(pointers);
  await store.create(INDEX_FILE, content);
  return content;
}
