import type { Frontmatter, MemoryType } from "./fact.ts";
import { MEMORY_TYPES, parseFact } from "./fact.ts";
import { INDEX_FILE } from "./store.ts";
import type { MemoryStore } from "./store.ts";

/**
 * The index (`MEMORY.md`) is *derived*, never hand-edited. Agents write fact
 * files; reindex regenerates the index from their frontmatter. This keeps the
 * one shared, mutable file off the concurrent-write path.
 */

interface IndexEntry {
  file: string;
  frontmatter: Frontmatter;
}

const TYPE_HEADINGS: Record<MemoryType, string> = {
  user: "User",
  feedback: "Feedback",
  project: "Project",
  reference: "Reference",
};

export function renderIndex(entries: IndexEntry[]): string {
  const lines: string[] = [
    "# Memory index",
    "",
    "<!-- Generated by mdmem from fact frontmatter. Do not edit by hand. -->",
    "",
  ];

  if (entries.length === 0) {
    lines.push("_No memories yet._", "");
    return lines.join("\n");
  }

  for (const type of MEMORY_TYPES) {
    const group = entries
      .filter((e) => e.frontmatter.metadata.type === type)
      .toSorted((a, b) => a.frontmatter.name.localeCompare(b.frontmatter.name));
    if (group.length === 0) {
      continue;
    }
    lines.push(`## ${TYPE_HEADINGS[type]}`, "");
    for (const e of group) {
      lines.push(
        `- [${e.frontmatter.name}](${e.file}) — ${e.frontmatter.description}`
      );
    }
    lines.push("");
  }

  return lines.join("\n");
}

export async function reindex(store: MemoryStore): Promise<string> {
  const files = await store.listFacts();
  // Read the facts concurrently, then parse them in file order.
  const raws = await Promise.all(
    files.map(async (file) => ({ file, raw: await store.view(file) }))
  );
  const entries: IndexEntry[] = raws.map(({ file, raw }) => ({
    file,
    frontmatter: parseFact(raw).frontmatter,
  }));
  const content = renderIndex(entries);
  await store.create(INDEX_FILE, content);
  return content;
}
